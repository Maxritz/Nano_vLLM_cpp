"""
test_gguf2vk.py — no pytest dependency, plain assert-based runner.

Run: python3 test_gguf2vk.py [path/to/extra_test_model.gguf ...]

Test tiers:
  1. Legacy dequant — hand-computed expected values (not generated by the
     function under test), catches real sign/shift/byte-order bugs.
  2. Requant + relayout round-trip — programmatic, checks losslessness
     (relayout) and bounded error (requant, since int8 quantization is lossy
     by design).
  3. K-quant (Q4_K/Q6_K) structural — runs against whatever real GGUF tensors
     are available, checks no crash / finite values / right element count.
     Does NOT prove the math is correct, only that it doesn't fall over.
  4. Integration — full convert.py pipeline against any uploaded .gguf files
     found, end to end, checking the output file is written and openable.
"""

